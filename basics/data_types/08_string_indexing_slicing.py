''' String indexing slicing is techniques in python for accessing
specific characters or parts of a string '''

language = "Python Programming"

print(language[0]) # Displaying the first character
print(language[-1]) # Displaying the last character
print(language[2]) # Displaying character at index 2
print(language[0:5]) # Displaying the first 5 characters
print(language[7:18]) # Displaying word 'Programming' using the slicing technique
print(language[::-1]) # Displaying inverted text 